<?php

declare(strict_types=1);

namespace Matma\Php\Indexing;

use FilesystemIterator;
use InvalidArgumentException;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use RuntimeException;
use Matma\Php\Analysis\SourceInventory;
use Symfony\Component\Yaml\Yaml;

final class ManifestWriter
{
    public const HEADER = "# AUTO-GENERATED BY MATMA AST INDEXER TOOL - DO NOT EDIT MANUALLY\n";

    public function __construct(
        private readonly string $projectRoot,
        private readonly string $testsRoot,
    ) {
    }

    /**
     * Never overwrite files that do not carry MATMA's ownership header.
     * A full, safe preflight occurs before writes or stale cleanup.
     *
     * @param array<string, array<string, mixed>> $manifests
     * @param array<string, mixed>|null $metadata
     * @return array{written: list<string>, unchanged: list<string>, removed: list<string>}
     */
    public function write(array $manifests, ?array $metadata = null): array
    {
        $mirrorDirectory = $this->mirrorDirectory();
        $desired = [];
        foreach ($manifests as $manifest) {
            $path = SourceInventory::absolutePath($this->projectRoot, $manifest['mirrors']['manifest']);
            $path = SourceInventory::normalize($path);
            if (! str_starts_with($path, $mirrorDirectory.'/')
                || preg_match('~(^|/)\.\.(/|$)~', $path) === 1
                || ! str_ends_with($path, '.auto.yaml')) {
                throw new InvalidArgumentException('Manifest path escapes configured tests/mirror root: '.$path);
            }

            $this->assertNoSymlinkAncestors($path);
            $desired[$path] = self::HEADER.Yaml::dump($manifest, 6, 2);
        }
        if ($metadata !== null) {
            $path = $mirrorDirectory.'/'.IndexMetadata::NAME;
            $this->assertNoSymlinkAncestors($path);
            $desired[$path] = self::HEADER.Yaml::dump($metadata, 6, 2);
        }
        ksort($desired, SORT_STRING);

        foreach ($desired as $path => $contents) {
            if (is_file($path) && ! $this->isOwned($path)) {
                throw new RuntimeException('Refusing to overwrite non-MATMA manifest: '.$path);
            }
            if (file_exists($path) && ! is_file($path)) {
                throw new RuntimeException('Manifest destination is not a regular file: '.$path);
            }
        }

        $result = ['written' => [], 'unchanged' => [], 'removed' => []];

        foreach ($desired as $path => $contents) {
            if (is_file($path) && file_get_contents($path) === $contents) {
                $result['unchanged'][] = $this->displayPath($path);
                continue;
            }

            $folder = dirname($path);
            if (! is_dir($folder) && ! mkdir($folder, 0775, true) && ! is_dir($folder)) {
                throw new RuntimeException('Failed to create manifest directory: '.$folder);
            }

            $temporary = tempnam($folder, '.matma-');
            if ($temporary === false) {
                throw new RuntimeException('Unable to allocate temporary manifest in '.$folder);
            }

            try {
                if (file_put_contents($temporary, $contents) !== strlen($contents)) {
                    throw new RuntimeException('Failed to write temporary manifest for '.$path);
                }
                if (! rename($temporary, $path)) {
                    throw new RuntimeException('Failed to atomically replace manifest: '.$path);
                }
                $result['written'][] = $this->displayPath($path);
            } finally {
                if (is_file($temporary)) {
                    unlink($temporary);
                }
            }
        }

        // Prune only our own generated YAML files. Leave hand-written files
        // and the directory structure entirely untouched.
        if (is_dir($mirrorDirectory)) {
            $iterator = new RecursiveIteratorIterator(
                new RecursiveDirectoryIterator($mirrorDirectory, FilesystemIterator::SKIP_DOTS),
            );
            foreach ($iterator as $file) {
                if ($file->isLink() || ! $file->isFile()) {
                    continue;
                }
                $path = SourceInventory::normalize($file->getPathname());
                if (! str_ends_with($path, '.auto.yaml') || isset($desired[$path]) || ! $this->isOwned($path)) {
                    continue;
                }
                if (! unlink($path)) {
                    throw new RuntimeException('Failed to remove stale generated manifest: '.$path);
                }
                $result['removed'][] = $this->displayPath($path);
            }
        }

        sort($result['written'], SORT_STRING);
        sort($result['unchanged'], SORT_STRING);
        sort($result['removed'], SORT_STRING);

        return $result;
    }

    private function mirrorDirectory(): string
    {
        $testsRoot = SourceInventory::normalize($this->testsRoot);
        if ($testsRoot === '' || $testsRoot === '/'
            || preg_match('~(^|/)\.\.(/|$)~', $testsRoot) === 1) {
            throw new InvalidArgumentException('Unsafe tests root for generated manifests.');
        }

        return rtrim(SourceInventory::absolutePath($this->projectRoot, $testsRoot), '/').'/mirror';
    }

    private function isOwned(string $path): bool
    {
        $handle = @fopen($path, 'rb');
        if ($handle === false) {
            return false;
        }
        try {
            return fread($handle, strlen(self::HEADER)) === self::HEADER;
        } finally {
            fclose($handle);
        }
    }

    private function assertNoSymlinkAncestors(string $path): void
    {
        $directory = dirname($path);
        while ($directory !== dirname($directory)) {
            if (is_link($directory)) {
                throw new RuntimeException('Refusing to write through symlink: '.$directory);
            }
            $directory = dirname($directory);
        }
        if (is_link($path)) {
            throw new RuntimeException('Refusing to overwrite symlink manifest: '.$path);
        }
    }

    private function displayPath(string $path): string
    {
        return SourceInventory::projectRelative($this->projectRoot, $path);
    }
}
